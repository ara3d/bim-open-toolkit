#!/usr/bin/env node
// Generates bimopenflow/web/packages/app/src/templates.generated.ts, the start
// page's catalog of flow templates, from the sample folders the host seeds.
//
//   node scripts/build-flow-templates.mjs           write the file
//   node scripts/build-flow-templates.mjs --check   exit 1 when the committed file differs
//
// A template is every graph document (a JSON file with a `structure.nodes`
// array) in samples/analyses and samples/*-analyses, plus each entry of
// samples/duckdb-analyses/workflows.json. Its description is the second cell
// of the folder README's table row whose first cell is the id in backticks.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const samples = join(root, 'samples');
const outFile = join(root, 'bimopenflow/web/packages/app/src/templates.generated.ts');

/** Maps each backticked id in the first cell of a README table row to its second cell. */
function readmeDescriptions(folderDir) {
  const readme = join(folderDir, 'README.md');
  const map = new Map();
  if (!existsSync(readme)) return map;
  for (const line of readFileSync(readme, 'utf8').split(/\r?\n/)) {
    const cells = line.trim().split('|').slice(1, -1).map((c) => c.trim());
    const id = /^`([^`]+)`$/.exec(cells[0] ?? '')?.[1];
    if (id && cells.length >= 2 && !map.has(id)) map.set(id, cells[1].replaceAll('`', ''));
  }
  return map;
}

const isGraph = (doc) => Array.isArray(doc?.structure?.nodes);

function template(id, folder, title, description, graph) {
  const kinds = [...new Set(graph.structure.nodes.map((n) => String(n.kind)))].sort();
  return { id, folder, title, description, nodeCount: graph.structure.nodes.length, kinds };
}

/** Reads one folder's templates and the files skipped as not graph documents. */
function readFolder(folder) {
  const dir = join(samples, folder);
  const described = readmeDescriptions(dir);
  const templates = [];
  const skipped = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const doc = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    if (folder === 'duckdb-analyses' && file === 'workflows.json' && Array.isArray(doc)) {
      for (const w of doc.filter((e) => isGraph(e?.graph))) {
        templates.push(template(w.id, folder, w.title || w.id, described.get(w.id) ?? w.description ?? '', w.graph));
      }
      continue;
    }
    if (!isGraph(doc)) { skipped.push(`${folder}/${file}`); continue; }
    const id = file.slice(0, -'.json'.length);
    templates.push(template(id, folder, id, described.get(id) ?? '', doc));
  }
  return { templates, skipped };
}

function collect() {
  const folders = readdirSync(samples, { withFileTypes: true })
    .filter((d) => d.isDirectory() && (d.name === 'analyses' || d.name.endsWith('-analyses')))
    .map((d) => d.name)
    .sort();
  const templates = [];
  const skipped = [];
  for (const folder of folders) {
    const r = readFolder(folder);
    templates.push(...r.templates);
    skipped.push(...r.skipped);
  }
  templates.sort((a, b) => (a.folder === b.folder ? cmp(a.id, b.id) : cmp(a.folder, b.folder)));
  return { templates, skipped };
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function render(templates) {
  return [
    '// Generated by scripts/build-flow-templates.mjs from samples/analyses and',
    '// samples/*-analyses. Do not edit; rerun the script after changing a sample.',
    'import type { FlowTemplate } from "./templates.js";',
    '',
    'export const TEMPLATES: readonly FlowTemplate[] = [',
    ...templates.map((t) => `  ${JSON.stringify(t)},`),
    '];',
    '',
  ].join('\n');
}

/** Names the template ids added, removed, or changed between two generated files. */
function diffSummary(before, after) {
  const entries = (text) => new Map(text.split('\n')
    .filter((l) => l.startsWith('  {'))
    .map((l) => [JSON.parse(l.trim().replace(/,$/, '')).id, l]));
  const a = entries(before);
  const b = entries(after);
  const lines = [];
  for (const [id, l] of b) if (!a.has(id)) lines.push(`  added   ${id}`); else if (a.get(id) !== l) lines.push(`  changed ${id}`);
  for (const id of a.keys()) if (!b.has(id)) lines.push(`  removed ${id}`);
  return lines.length ? lines.join('\n') : '  header or formatting differs';
}

const { templates, skipped } = collect();
const text = render(templates);
const rel = relative(root, outFile).split(sep).join('/');
for (const s of skipped) console.log(`skipped ${s}: no structure.nodes array`);

if (process.argv.includes('--check')) {
  const committed = existsSync(outFile) ? readFileSync(outFile, 'utf8').replaceAll('\r\n', '\n') : '';
  if (committed !== text) {
    console.error(`${rel} is out of date; run node scripts/build-flow-templates.mjs`);
    console.error(diffSummary(committed, text));
    process.exit(1);
  }
  console.log(`${rel} is up to date (${templates.length} templates)`);
} else {
  writeFileSync(outFile, text);
  console.log(`wrote ${rel} (${templates.length} templates)`);
}
